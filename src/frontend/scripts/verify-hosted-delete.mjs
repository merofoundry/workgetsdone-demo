import './stage-guard.mjs';
import { chromium } from '@playwright/test';
import { readFileSync, appendFileSync, writeFileSync, mkdirSync } from 'node:fs';
const root = new URL('../../', import.meta.url);
const evidence = new URL('verification/2026-10-11-full-build/', root);
const base = process.env.WGD_BASE || 'https://workgetsdone.staging.merofoundry.app';
const checks = [];
const check = (name, passed, detail) => { checks.push({ name, passed: !!passed, evidence: detail }); console.log(`${passed ? 'PASS' : 'FAIL'} ${name}: ${JSON.stringify(detail)}`); if (!passed) throw new Error(name); };
const passwordFor = name => {
  const line = readFileSync(new URL(`.env-${name}`, root), 'utf8').split('\n').find(line => line.startsWith(`${name.toUpperCase()}_PASSWORD=`));
  if (!line) throw new Error(`Missing ${name} verification credential`);
  return line.slice(line.indexOf('=') + 1).replace(/^['"]|['"]$/g, '').trim();
};
mkdirSync(evidence, { recursive: true });
const browser = await chromium.launch({ headless: true });
let failure;
async function signIn(name) {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const page = await context.newPage(); page.errors = []; page.on('pageerror', error => page.errors.push(error.message));
  await page.goto(base + '/sign-in', { waitUntil: 'domcontentloaded' });
  await page.getByRole('heading', { name: 'Sign in to your work' }).waitFor();
  await page.getByLabel('Email', { exact: true }).fill(`${name}@workgetsdone.test`);
  await page.getByLabel('Password', { exact: true }).fill(passwordFor(name));
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: /^Account:/ }).waitFor();
  return { context, page };
}
try {
  const bob = await signIn('bob'); const page = bob.page;
  check('bob: signed in', true, { path: new URL(page.url()).pathname });
  const stamp = Date.now().toString(36); const company = `WGD-MATRIX delete ${stamp}`; const projectName = `WGD-MATRIX delete project ${stamp}`; const taskTitle = `WGD-MATRIX delete task ${stamp}`;
  await page.goto(base + '/companies');
  await page.getByRole('button', { name: 'New company' }).click();
  const createCompany = page.getByRole('dialog', { name: 'New company' });
  await createCompany.getByLabel('Name', { exact: true }).fill(company);
  await createCompany.getByRole('button', { name: 'Create company' }).click();
  await page.getByRole('heading', { name: company, exact: true }).waitFor();
  const companyPath = new URL(page.url()).pathname;
  check('bob: created the WGD-MATRIX company', /^\/companies\/[0-9a-f-]{36}$/.test(companyPath), { companyPath });
  await page.goto(base + '/projects');
  await page.getByRole('button', { name: 'New project' }).click();
  const createProject = page.getByRole('dialog', { name: 'New project' });
  await createProject.getByLabel('Name', { exact: true }).fill(projectName);
  await createProject.getByLabel('Description', { exact: true }).fill('Created by the hosted delete check.');
  await createProject.getByLabel('Company', { exact: true }).fill(company);
  await createProject.locator('.picker-results').getByRole('button', { name: new RegExp(company) }).click({ timeout: 60000 });
  await createProject.getByRole('button', { name: 'Create project' }).click();
  await page.getByRole('heading', { name: projectName, exact: true }).waitFor();
  const projectPath = new URL(page.url()).pathname;
  check('bob: created a project under the company', /^\/projects\/[0-9a-f-]{36}$/.test(projectPath), { projectPath });
  await page.getByRole('button', { name: /^New task/ }).click();
  const createTask = page.getByRole('dialog', { name: 'New task' });
  await createTask.getByLabel('Task name').fill(taskTitle);
  await createTask.getByRole('button', { name: 'Create task' }).click();
  await page.getByRole('dialog').waitFor({ state: 'detached' });
  await page.getByRole('link', { name: taskTitle }).waitFor();
  check('bob: the project has a task', true, { taskTitle });
  await page.goto(base + companyPath);
  await page.getByRole('heading', { name: company, exact: true }).waitFor();
  await page.locator('.page-header').getByRole('button', { name: 'Delete', exact: true }).click();
  const blocked = page.getByRole('dialog', { name: 'Delete company?' });
  await blocked.getByText(/1 project still references this company/).waitFor();
  check('bob: company delete preview names the blocking project', true, { text: (await blocked.innerText()).replace(/\s+/g, ' ').slice(0, 300) });
  check('bob: company Confirm is disabled', await blocked.getByRole('button', { name: 'Confirm' }).isDisabled(), {});
  await page.screenshot({ path: new URL('hosted-delete-blocked-bob.png', evidence).pathname, fullPage: true });
  await blocked.getByRole('button', { name: 'Cancel' }).click();
  await page.goto(base + projectPath);
  await page.getByRole('heading', { name: projectName, exact: true }).waitFor();
  await page.locator('.page-header').getByRole('button', { name: 'Delete', exact: true }).click();
  const projectDialog = page.getByRole('dialog', { name: 'Delete project?' });
  await projectDialog.getByRole('radio', { name: 'Delete everything under it' }).check();
  await page.screenshot({ path: new URL('hosted-delete-project-bob.png', evidence).pathname, fullPage: true });
  await projectDialog.getByRole('button', { name: 'Confirm' }).click();
  await page.waitForURL(url => url.pathname === '/projects', { timeout: 60000 });
  check('bob: project deleted with its task, landed on /projects', true, { path: new URL(page.url()).pathname });
  await page.goto(base + companyPath);
  await page.getByRole('heading', { name: company, exact: true }).waitFor();
  await page.locator('.page-header').getByRole('button', { name: 'Delete', exact: true }).click();
  const final = page.getByRole('dialog', { name: 'Delete company?' });
  await final.getByRole('button', { name: 'Confirm' }).waitFor();
  await page.waitForFunction(() => { const b = [...document.querySelectorAll('dialog button')].find(el => el.textContent === 'Confirm'); return b && !b.disabled; }, null, { timeout: 30000 });
  await final.getByRole('button', { name: 'Confirm' }).click();
  await page.waitForURL(url => url.pathname === '/companies', { timeout: 60000 });
  check('bob: company deleted, landed on /companies', true, { path: new URL(page.url()).pathname });
  await page.goto(base + companyPath);
  await page.getByText('This company could not be found.').waitFor();
  check('bob: the deleted company reads as not found', true, {});
  check('no script errors', page.errors.length === 0, { errors: page.errors });
  await bob.context.close();
} catch (error) { failure = error.message; console.error(failure); }
finally {
  await browser.close();
  writeFileSync(new URL('hosted-delete-results.json', evidence), JSON.stringify({ at: new Date().toISOString(), base, checks, failure: failure || null }, null, 2));
  appendFileSync(new URL('BUILD_LOG.md', root), `\n\n### ${new Date().toISOString()} — Hosted delete dialog browser verification (Task 14)\n\n${checks.filter(item => item.passed).length}/${checks.length} checks passed. Evidence: ${evidence.pathname.slice(root.pathname.length)}hosted-delete-results.json.\n${failure ? `FAILED: ${failure}\n` : ''}`);
}
if (failure) process.exit(1);
